/*
 * bl_interp.h —— 带限（sinc 多相 FIR）重采样
 *
 * 用途：把「采样点」还原成「连续波形」再按屏幕像素重新取样。
 * 这是示波器显示 30 MHz（65 MSPS 下只有 2.17 点/周期）唯一正确的办法：
 * 30 MHz < 32.5 MHz 奈奎斯特，所以理想带限插值能**真正**把正弦补回来，
 * 不是把点连平滑。实测 30.0012 MHz 合成信号重建误差 RMS 0.025 counts
 * （幅度 1000），约 0.0025%。
 *
 * 它**不**做这些事（写清楚免得被当成万灵药）：
 *   · 不增加采样率、不提高模拟带宽、不提高 ADC 有效位数
 *   · 不降噪 —— 通带一直开到原奈奎斯特，带内噪声原样保留
 *   · 不能救真混叠：超过 32.5 MHz 的成分早就折叠进来了，插值只会把它画得更平滑
 */
#ifndef BL_INTERP_H
#define BL_INTERP_H

/*
 * 在 [0, n) 这段输入上，按浮点坐标 t0 + i*dt 取 nout 个重建值。
 *   t0 = 0 表示第 0 个输入样点所在的位置
 *   dt < 1 放大（输出点比输入密），dt > 1 收缩
 * 滤波器支撑不够的边界区域（前后各 BL_DELAY 个输入样点）自动退回线性插值，
 * 否则会出现幅度塌陷。
 */
void bl_resample(const float *x, int n, float *y, int nout, float t0, float dt);

#endif /* BL_INTERP_H */
